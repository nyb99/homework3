#!/usr/bin/env python3
"""Generate an 8x16 ASCII bitmap font (0x20..0x7E) for the SSD1306 OLED driver.

The glyphs are rendered from the Windows "Consolas" monospace font, thresholded
to 1 bpp and packed into the page format used by the OLED driver:
  each character = 8 columns x 2 pages, byte order = column-major per page.

Output: Core/Inc/oledfont.h  (const uint8_t OLED_F8x16[])
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FONT_PATH = r"C:\Windows\Fonts\consola.ttf"
SIZE = 14
X_OFFSET = 0
BASELINE = 12
THRESHOLD = 110
CELL_W, CELL_H = 8, 16
FIRST, LAST = 0x20, 0x7E


def render(font, ch):
    img = Image.new("L", (CELL_W, CELL_H), 0)
    d = ImageDraw.Draw(img)
    d.text((X_OFFSET, BASELINE), ch, fill=255, font=font, anchor="ls")
    px = img.load()
    cols = []
    for x in range(CELL_W):
        top = 0
        bot = 0
        for y in range(8):
            if px[x, y] >= THRESHOLD:
                top |= 1 << y
            if px[x, y + 8] >= THRESHOLD:
                bot |= 1 << y
        cols.append((top, bot))
    return cols


def check_clip(px_img):
    px = px_img.load()
    for x in range(CELL_W):
        if px[x, 0] >= THRESHOLD or px[x, CELL_H - 1] >= THRESHOLD:
            return True
    return False


def ascii_art(img):
    px = img.load()
    return ["".join("#" if px[x, y] >= THRESHOLD else "." for x in range(img.width))
            for y in range(img.height)]


def main():
    font = ImageFont.truetype(FONT_PATH, SIZE)
    out = []
    clipped = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        img = Image.new("L", (CELL_W, CELL_H), 0)
        ImageDraw.Draw(img).text((X_OFFSET, BASELINE), ch, fill=255,
                                 font=font, anchor="ls")
        if check_clip(img):
            clipped.append(ch)

    if clipped:
        print("WARNING clipped glyphs:", "".join(clipped))

    # Visual check of a representative string
    sample = "STATE: PAUSE"
    canvas = Image.new("L", (CELL_W * len(sample), CELL_H), 0)
    for i, ch in enumerate(sample):
        img = Image.new("L", (CELL_W, CELL_H), 0)
        ImageDraw.Draw(img).text((X_OFFSET, BASELINE), ch, fill=255,
                                 font=font, anchor="ls")
        canvas.paste(img, (i * CELL_W, 0))
    rows = ascii_art(canvas)
    print(sample)
    print("\n".join(rows))

    for code in range(FIRST, LAST + 1):
        cols = render(font, chr(code))
        for top, bot in cols:
            out.append(top)
        for top, bot in cols:
            out.append(bot)

    lines = []
    for i in range(0, len(out), 16):
        lines.append("  " + ", ".join("0x%02X" % b for b in out[i:i + 16]) + ",")
    body = "\n".join(lines)

    header = f"""/**
  ******************************************************************************
  * @file    oledfont.h
  * @brief   8x16 ASCII bitmap font (0x20..0x7E) for the software I2C OLED.
  *
  *          Layout: every character is 8 pixels wide and 16 pixels high.
  *          Bytes are column-major: for each of the 8 columns the first byte
  *          holds the top page (y = 0..7, LSB = top) and the second byte holds
  *          the bottom page (y = 8..15, LSB = y = 8).
  *          Character index = (ASCII code - 0x20), 16 bytes per character.
  *
  *          Generated by tools/gen_oled_font.py from the Windows "Consolas"
  *          monospace font (size {SIZE}px, threshold {THRESHOLD}).
  ******************************************************************************
  */
#ifndef __OLEDFONT_H
#define __OLEDFONT_H

#include <stdint.h>

#define OLED_FONT_WIDTH   8u
#define OLED_FONT_HEIGHT  16u
#define OLED_FONT_FIRST   0x20u
#define OLED_FONT_LAST    0x7Eu
#define OLED_FONT_BYTES   (((OLED_FONT_LAST - OLED_FONT_FIRST) + 1u) * 16u)

static const uint8_t OLED_F8x16[OLED_FONT_BYTES] = {{
{body}
}};

#endif /* __OLEDFONT_H */
"""
    dst = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "Core", "Inc", "oledfont.h")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)
    print("\nwrote", dst, len(out), "bytes")


if __name__ == "__main__":
    sys.exit(main())
